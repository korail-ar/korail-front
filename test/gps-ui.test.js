import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';

test('내 위치 구독은 실시간 갱신되고 종료 시 정리된다', async () => {
  const html = await readFile(new URL('../public/gps-test.html', import.meta.url), 'utf8');
  const settings = JSON.parse(await readFile(new URL('../public/gps-calibration.json', import.meta.url)));
  const points = JSON.parse(await readFile(new URL('../public/gps-points.json', import.meta.url)));
  const graph = { floor: 3, mapId: 'daejeon-station-3F-map.svg', weightUnit: 's', nodes: [{ id: 'A', x: 980, y: 1460 }, { id: 'B', x: 1100, y: 1460 }, { id: 'C', x: 980, y: 1600 }, { id: 'D', x: 1100, y: 1600 }], edges: [{ id: 'E', source: 'A', target: 'B', weight: 10, bidirectional: true, verified: false }, { id: 'CD', source: 'C', target: 'D', weight: 10, bidirectional: true, verified: false }, { id: 'DB', source: 'D', target: 'B', weight: 10, bidirectional: true, verified: false }], places: [{ id: 'P1', name: '출발', x: 980, y: 1460, nodeId: 'A' }, { id: 'P2', name: '도착', x: 1100, y: 1460, nodeId: 'B' }] };
  const dom = new JSDOM(html, { url: 'https://example.test/gps-test.html' });
  const originals = Object.fromEntries(['window', 'document', 'navigator', 'fetch'].map(key => [key, Object.getOwnPropertyDescriptor(globalThis, key)]));
  const interval = globalThis.setInterval;
  let success, clearCount = 0, watchCount = 0, centered = 0;
  const requested = [];
  try {
    Object.defineProperty(globalThis, 'window', { configurable: true, value: dom.window });
    Object.defineProperty(globalThis, 'document', { configurable: true, value: dom.window.document });
    Object.defineProperty(globalThis, 'navigator', { configurable: true, value: { geolocation: { watchPosition(callback) { success = callback; watchCount++; return watchCount; }, clearWatch() { clearCount++; } } } });
    Object.defineProperty(dom.window, 'isSecureContext', { configurable: true, value: true });
    globalThis.setInterval = () => 1;
    globalThis.fetch = async path => { requested.push(path); return { ok: true, json: async () => path.includes('calibration') ? settings : path.includes('points') ? points : graph }; };
    await import(`../public/gps-diagnostics.js?test=${Date.now()}`);
    assert.deepEqual(requested, ['/gps-calibration.json', '/gps-points.json', '/assets/json/gps-test-floor-3.json']);
    await new Promise(resolve => setImmediate(resolve));
    document.getElementById('testFrom').value = 'P1';
    document.getElementById('testTo').value = 'P2';
    document.getElementById('testRoute').click();
    assert.equal(document.querySelectorAll('#testRouteLayer polyline').length, 2);
    document.getElementById('viewport').scrollIntoView = () => { centered++; };
    const routeShape = document.querySelector('#testRouteLayer [data-role="gps-test-route"]');
    const routeGeometry = routeShape.getAttribute('points');
    document.getElementById('gpsOn').click();
    assert.equal(watchCount, 1);
    assert.equal(document.getElementById('experimental').checked, true);
    let tick = 0;
    const emit = latitude => success({ coords: { latitude, longitude: 127.434, accuracy: 5 }, timestamp: Date.now() + tick++ * 1000 });
    emit(36.332);
    assert.equal(centered, 1);
    assert.match(document.getElementById('gpsStatus').textContent, /실시간 GPS.*추정 위치/);
    assert.match(document.getElementById('mapFixStatus').textContent, /실시간 GPS.*추정 위치/);
    assert.match(document.getElementById('routeDistance').textContent, /SVG 좌표 단위/);
    const first = document.querySelector('#gpsLayer circle:last-of-type').getAttribute('cx');
    emit(36.33201);
    assert.notEqual(document.querySelector('#gpsLayer circle:last-of-type').getAttribute('cx'), first);
    assert.equal(routeShape.getAttribute('points'), routeGeometry);
    assert.equal(routeShape.closest('svg'), document.querySelector('#gpsLayer circle').closest('svg'));
    document.getElementById('checkpointPlace').value = 'P1';
    document.getElementById('useCheckpoint').click();
    assert.match(document.getElementById('correctionStatus').textContent, /시설 대표점 기준 임시 맞춤/);
    const map = document.getElementById('map');
    map.getScreenCTM = () => ({ inverse: () => ({}) });
    map.createSVGPoint = () => ({ x: 0, y: 0, matrixTransform() { return { x: this.x, y: this.y }; } });
    document.getElementById('editPosition').click();
    map.dispatchEvent(new dom.window.MouseEvent('click', { clientX: 1040, clientY: 1600 }));
    assert.equal(document.querySelector('[data-role="current-location"]').getAttribute('cy'), '1600');
    emit(36.33201); emit(36.33201);
    assert.match(document.getElementById('testRouteStatus').textContent, /재탐색/);
    document.getElementById('rotate').click();
    assert.equal(document.getElementById('map').style.transform, 'rotate(90deg)');
    document.getElementById('floor').value = '2';
    document.getElementById('floor').dispatchEvent(new dom.window.Event('change'));
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(document.getElementById('gpsLayer').children.length, 0);
    assert.match(document.getElementById('correctionStatus').textContent, /수동 맞춤 없음/);
    document.getElementById('gpsOff').click();
    assert.equal(clearCount, 1);
    assert.equal(document.getElementById('gpsLayer').children.length, 0);
  } finally {
    globalThis.setInterval = interval;
    for (const [key, descriptor] of Object.entries(originals)) descriptor ? Object.defineProperty(globalThis, key, descriptor) : delete globalThis[key];
    dom.window.close();
  }
});
